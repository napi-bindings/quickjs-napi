#!/usr/bin/env python3
"""Generates src/stubs_generated.c.

Every function declared in the Node-API headers must be exported by the host
executable, otherwise addons fail to load (RTLD_NOW on Linux/macOS, import
resolution on Windows). Functions that are not implemented yet get a stub that
returns napi_generic_failure and records a descriptive last-error message.

A function counts as implemented when a definition `NAPI_CDECL <name>(`
appears in any src/*.c file other than the generated one.

Usage:
    tools/gen_stubs.py           regenerate src/stubs_generated.c
    tools/gen_stubs.py --check   exit 1 if the file is out of date
"""

import glob
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from napi_decls import ROOT, parse_declarations  # noqa: E402

OUTPUT = os.path.join(ROOT, "src", "stubs_generated.c")
_DEF_RE = re.compile(r"NAPI_CDECL\s+(\w+)\s*\(")


def implemented_names():
    names = set()
    for path in glob.glob(os.path.join(ROOT, "src", "*.c")):
        if os.path.abspath(path) == OUTPUT:
            continue
        with open(path, encoding="utf-8") as f:
            names.update(_DEF_RE.findall(f.read()))
    return names


def render(decls, implemented):
    stubs = [d for d in decls if d.name not in implemented]
    lines = [
        "/*",
        " * GENERATED by tools/gen_stubs.py - do not edit.",
        " *",
        " * Node-API functions declared in the headers but not implemented yet.",
        " * They exist so that the host exports the complete symbol set and",
        " * addons referencing them still load; calling one returns",
        " * napi_generic_failure with a descriptive napi_get_last_error_info().",
        " *",
        " * Implemented: %d / %d functions." % (len(decls) - len(stubs), len(decls)),
        " */",
        '#include "qjsnapi_internal.h"',
        "",
        "#if defined(__GNUC__) || defined(__clang__)",
        '#pragma GCC diagnostic ignored "-Wunused-parameter"',
        "#endif",
        "",
    ]
    for d in stubs:
        if d.ret != "napi_status":
            raise SystemExit(
                "%s returns %s: implement it by hand, stubs only cover "
                "napi_status functions" % (d.name, d.ret)
            )
        params = ", ".join(d.params) if d.params else "void"
        env_arg = "env" if d.first_param_is_env else "NULL"
        lines.append("NAPI_EXTERN napi_status NAPI_CDECL")
        lines.append("%s(%s) {" % (d.name, params))
        lines.append('  return qn_not_implemented(%s, "%s");' % (env_arg, d.name))
        lines.append("}")
        lines.append("")
    if not stubs:
        lines.append("/* Every Node-API function is implemented. */")
        lines.append("typedef int qn_stubs_generated_empty;")
        lines.append("")
    return "\n".join(lines)


def main(argv):
    decls = parse_declarations()
    content = render(decls, implemented_names())
    if "--check" in argv:
        try:
            with open(OUTPUT, encoding="utf-8") as f:
                current = f.read()
        except FileNotFoundError:
            current = None
        if current != content:
            print("src/stubs_generated.c is out of date: run tools/gen_stubs.py")
            return 1
        return 0
    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(content)
    stubs = content.count("qn_not_implemented(")
    print("wrote %s (%d declarations, %d stubs)" % (OUTPUT, len(decls), stubs))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
